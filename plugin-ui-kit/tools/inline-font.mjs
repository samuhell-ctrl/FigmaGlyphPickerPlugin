#!/usr/bin/env node
/* =============================================================================
   INLINE FONT -> @font-face  (base64 data: URI)

   A data: URI is not a network request, so an inlined font needs NO entry in
   manifest.json networkAccess — the manifest can stay ["none"]. That is the
   only font setup that cannot break after publishing.

   Usage:
     node tools/inline-font.mjs --family "Plugin UI" \
       fonts/Inter-Regular.woff2:400 \
       fonts/Inter-SemiBold.woff2:600 \
       --out src/fonts.css

   Each positional arg is  path[:weight[:style]]   (default 400, normal).
   Omit --out to print to stdout.

   SUBSET FIRST. A full Latin woff2 is ~25–40 kB; base64 adds ~33%. Keep the
   whole built ui.html comfortably under a megabyte:
     pip install fonttools brotli
     pyftsubset Inter.ttf --flavor=woff2 --output-file=Inter-Regular.woff2 \
       --unicodes="U+0020-007E,U+00A0-00FF,U+2018-201D,U+2026,U+2013-2014" \
       --layout-features="kern,liga"
   ============================================================================= */

import { readFile, writeFile } from "node:fs/promises";
import { basename, extname } from "node:path";

const MIME = { ".woff2": "font/woff2", ".woff": "font/woff", ".ttf": "font/ttf", ".otf": "font/otf" };
const FORMAT = { ".woff2": "woff2", ".woff": "woff", ".ttf": "truetype", ".otf": "opentype" };

const argv = process.argv.slice(2);
const flag = (name, fallback) => {
  const i = argv.indexOf(name);
  return i === -1 ? fallback : argv[i + 1];
};
const family = flag("--family", "Plugin UI");
const out = flag("--out", null);
const files = argv.filter((a, i) => !a.startsWith("--") && !["--family", "--out"].includes(argv[i - 1]));

if (!files.length) {
  console.error("No font files given. See the header of this file for usage.");
  process.exit(1);
}

const blocks = [];
let total = 0;

for (const entry of files) {
  const [path, weight = "400", style = "normal"] = entry.split(":");
  const ext = extname(path).toLowerCase();
  if (!MIME[ext]) {
    console.error(`Unsupported font format: ${path}`);
    process.exit(1);
  }
  if (ext !== ".woff2") {
    console.error(`! ${basename(path)} is not woff2 — convert it first, the payload is 2–4x larger.`);
  }
  const buf = await readFile(path);
  total += buf.length;
  blocks.push(
    `@font-face {\n` +
    `  font-family: "${family}";\n` +
    `  font-style: ${style};\n` +
    `  font-weight: ${weight};\n` +
    `  font-display: block;\n` +
    `  src: url(data:${MIME[ext]};base64,${buf.toString("base64")}) format("${FORMAT[ext]}");\n` +
    `}`
  );
  console.error(`  ${basename(path)}  ${weight}/${style}  ${(buf.length / 1024).toFixed(1)} kB raw`);
}

const css =
  `/* Generated by tools/inline-font.mjs — do not edit by hand.\n` +
  `   data: URIs are not network requests: networkAccess can stay ["none"]. */\n\n` +
  blocks.join("\n\n") +
  `\n\n:root {\n  --k-font-ui: "${family}", -apple-system, BlinkMacSystemFont, system-ui, sans-serif;\n}\n`;

if (out) {
  await writeFile(out, css, "utf8");
  console.error(`\nwrote ${out} — ${(css.length / 1024).toFixed(1)} kB (${(total / 1024).toFixed(1)} kB of font data, +33% base64)`);
} else {
  process.stdout.write(css);
}
